import { z } from 'zod';
import type { TopicType, TagStatus } from '../types/journal';

export const ALLOWED_TOPIC_TAGS: readonly TopicType[] = [
  'work_study',
  'relationships',
  'family',
  'health',
  'money',
  'goals',
  'leisure',
  'other',
] as const;

export const TagSuggestionSchema = z.object({
  tags: z
    .array(
      z.enum([
        'work_study',
        'relationships',
        'family',
        'health',
        'money',
        'goals',
        'leisure',
        'other',
      ])
    )
    .max(3, 'Cannot have more than 3 tags'),
});

export type ValidatedTagSuggestion = z.infer<typeof TagSuggestionSchema>;

/** Timing and size of one model call. Contains no transcript or output text. */
export interface LlmCallStats {
  /** ms from the call until the first generated token (includes prefill). null if no token arrived. */
  firstTokenMs: number | null;
  /** ms for the whole call. */
  totalMs: number;
  /** Tokens generated by the model (decode), summed over the turn. */
  tokensGenerated: number | null;
  /** Tokens in the prompt the model read (prefill). */
  promptTokens: number | null;
  prefillMs: number | null;
  decodeMs: number | null;
  /** 'stop' | 'cancelled' | 'maxToolTurns' from the library. */
  finishReason: string;
  /** Length of the raw model output, including any <think> block. */
  rawChars: number;
  /** Length after removing <think> blocks. */
  answerChars: number;
  hadThinkBlock: boolean;
  /** Model reported ready when the call started. */
  modelLoaded: boolean;
  /** Increments each time the model session is (re)created. Same id across entries means no reload. */
  modelSessionId: number;
  /** 1-based count of calls made on this model session. */
  callIndexInSession: number;
}

export interface LlmCallResult {
  /** Model output with <think> blocks removed. */
  text: string;
  stats: LlmCallStats;
}

export type TagAttemptOutcome = 'valid' | 'invalid_json' | 'schema_error' | 'threw' | 'timeout';

/** One attempt, for the [TAG-TIMING] log line. Contains no transcript or output text. */
export interface TagAttemptRecord {
  attempt: 1 | 2;
  outcome: TagAttemptOutcome;
  promptChars: number;
  /** null when the call threw before returning stats. */
  stats: LlmCallStats | null;
  /** ms for this attempt as seen by the caller (always set, also when the call threw). */
  attemptMs: number;
}

export interface TagSuggestionResult {
  tags: TopicType[];
  status: TagStatus;
  llmMs: number;
  retryCount: number;
  attempts: TagAttemptRecord[];
}

/**
 * Defensive parser: Removes markdown code blocks, locates the JSON object
 * boundaries, and parses cleanly.
 */
function extractAndParseJson(raw: string): unknown {
  // Strip markdown code fences if present
  let clean = raw.trim();
  if (clean.includes('```')) {
    clean = clean.replace(/```(?:json)?\s*([\s\S]*?)\s*```/g, '$1').trim();
  }

  // Find enclosing JSON object { ... }
  const firstBrace = clean.indexOf('{');
  const lastBrace = clean.lastIndexOf('}');
  if (firstBrace === -1 || lastBrace === -1 || lastBrace < firstBrace) {
    throw new Error('No JSON object found in LLM response.');
  }

  const jsonSubstring = clean.substring(firstBrace, lastBrace + 1);
  return JSON.parse(jsonSubstring);
}

/**
 * Longest transcript slice sent to the model, in characters. Measured: a
 * 390-character Hinglish transcript cost about 350 prompt tokens and 6.5 s of
 * prefill on the phone, so the input is capped to keep prefill short. Tags are
 * then based on the first part of long entries.
 */
export const MAX_TAG_INPUT_CHARS = 500;

/**
 * Cuts text to at most `maxChars`, at the last whitespace before the limit so a
 * word is never split. Falls back to a hard cut if there is no whitespace.
 */
export function truncateForTagging(text: string, maxChars: number = MAX_TAG_INPUT_CHARS): string {
  const clean = text.replace(/\s+/g, ' ').trim();
  if (clean.length <= maxChars) return clean;
  const slice = clean.slice(0, maxChars);
  const lastSpace = slice.lastIndexOf(' ');
  return (lastSpace > maxChars * 0.6 ? slice.slice(0, lastSpace) : slice).trim();
}

/**
 * Short prompt. It deliberately contains no example answer with real tag
 * names: the 0.6B model copied the old example ({"tags": ["work_study",
 * "goals"]}) for every entry. The one-line topic hints help it tell them apart.
 */
const TOPIC_GUIDE = `work_study: job, office, college, exams
relationships: partner, friends, dating
family: parents, siblings, relatives, home
health: body, sleep, exercise, illness, mental health
money: spending, salary, bills, savings
goals: plans, habits, self-improvement
leisure: hobbies, movies, games, travel, eating out
other: none of the above`;

function buildPrompt(entry: string, correction: string | null): string {
  const fix = correction ? `\nYour last reply was rejected: ${correction}\n` : '';
  return `Choose 1 to 3 topics that this journal entry is mainly about.
Topics:
${TOPIC_GUIDE}
${fix}
Reply with only a JSON object whose "tags" key holds the chosen topic names, nothing else.

Entry: """${entry}"""`;
}

function buildInitialPrompt(entry: string): string {
  return buildPrompt(entry, null);
}

/** The exact first-attempt prompt the app sends, for the laptop cloud baseline. */
export function buildTagPrompt(transcript: string): string {
  return buildInitialPrompt(truncateForTagging(transcript));
}

/** Validates a model reply the same way the app does. Returns the tags or null. */
export function parseTagReply(raw: string): TopicType[] | null {
  try {
    const parsed = TagSuggestionSchema.safeParse(normalizeTagCase(extractAndParseJson(raw)));
    return parsed.success ? (parsed.data.tags as TopicType[]) : null;
  } catch {
    return null;
  }
}

function buildSchemaRetryPrompt(entry: string, errorMessage: string): string {
  return buildPrompt(entry, errorMessage);
}

function buildParseRetryPrompt(entry: string): string {
  return buildPrompt(entry, 'it was not a valid JSON object.');
}

function buildTimeoutRetryPrompt(entry: string): string {
  return buildPrompt(entry, 'it took too long. Reply with the JSON object only.');
}

/** Thrown by the caller's model function when an attempt exceeds its time limit. */
export class TagAttemptTimeoutError extends Error {
  readonly timeoutMs: number;
  constructor(timeoutMs: number) {
    super(`Tag attempt timed out after ${timeoutMs} ms`);
    this.name = 'TagAttemptTimeoutError';
    this.timeoutMs = timeoutMs;
  }
}

type AttemptEvaluation =
  | { outcome: 'valid'; tags: TopicType[] }
  | { outcome: 'schema_error'; errorMessage: string }
  | { outcome: 'invalid_json' | 'threw' | 'timeout' };

/**
 * Lowercases and trims tag strings before validation, and drops duplicates.
 * This does not invent or replace tags: anything not in the allowed list still
 * fails the schema.
 */
function normalizeTagCase(value: unknown): unknown {
  if (typeof value !== 'object' || value === null || !('tags' in value)) return value;
  const tags = (value as { tags: unknown }).tags;
  if (!Array.isArray(tags)) return value;
  const cleaned = tags.map((t) => (typeof t === 'string' ? t.trim().toLowerCase() : t));
  return { ...value, tags: [...new Set(cleaned)] };
}

async function runAttempt(
  prompt: string,
  sendLLMMessage: (prompt: string) => Promise<LlmCallResult>
): Promise<{ evaluation: AttemptEvaluation; stats: LlmCallStats | null; attemptMs: number }> {
  const start = performance.now();
  let call: LlmCallResult;
  try {
    call = await sendLLMMessage(prompt);
  } catch (err: unknown) {
    return {
      evaluation: { outcome: err instanceof TagAttemptTimeoutError ? 'timeout' : 'threw' },
      stats: null,
      attemptMs: Math.round(performance.now() - start),
    };
  }
  const attemptMs = Math.round(performance.now() - start);

  let parsed: unknown;
  try {
    parsed = extractAndParseJson(call.text);
  } catch {
    return { evaluation: { outcome: 'invalid_json' }, stats: call.stats, attemptMs };
  }

  const validation = TagSuggestionSchema.safeParse(normalizeTagCase(parsed));
  if (validation.success) {
    return {
      evaluation: { outcome: 'valid', tags: validation.data.tags as TopicType[] },
      stats: call.stats,
      attemptMs,
    };
  }
  return {
    evaluation: {
      outcome: 'schema_error',
      errorMessage: validation.error.issues.map((i) => i.message).join('; '),
    },
    stats: call.stats,
    attemptMs,
  };
}

/**
 * Executes on-device LLM topic tag suggestion with strict defensive parsing,
 * Zod schema validation, and exactly 1 retry upon failure.
 *
 * Never blocks the UI or saving. If both attempts fail, returns empty tags with
 * status 'failed' (no rule-based fallback).
 */
export async function suggestTopicTags(
  transcript: string,
  sendLLMMessage: (prompt: string) => Promise<LlmCallResult>
): Promise<TagSuggestionResult> {
  const startTime = performance.now();
  const attempts: TagAttemptRecord[] = [];
  const entry = truncateForTagging(transcript);

  // Attempt 1
  const firstPrompt = buildInitialPrompt(entry);
  const first = await runAttempt(firstPrompt, sendLLMMessage);
  attempts.push({
    attempt: 1,
    outcome: first.evaluation.outcome,
    promptChars: firstPrompt.length,
    stats: first.stats,
    attemptMs: first.attemptMs,
  });

  if (first.evaluation.outcome === 'valid') {
    return {
      tags: first.evaluation.tags,
      status: 'ok',
      llmMs: Math.round(performance.now() - startTime),
      retryCount: 0,
      attempts,
    };
  }

  // Attempt 2 (the single retry), with the specific problem from attempt 1
  const retryPrompt =
    first.evaluation.outcome === 'schema_error'
      ? buildSchemaRetryPrompt(entry, first.evaluation.errorMessage)
      : first.evaluation.outcome === 'timeout'
        ? buildTimeoutRetryPrompt(entry)
        : buildParseRetryPrompt(entry);
  const second = await runAttempt(retryPrompt, sendLLMMessage);
  attempts.push({
    attempt: 2,
    outcome: second.evaluation.outcome,
    promptChars: retryPrompt.length,
    stats: second.stats,
    attemptMs: second.attemptMs,
  });

  const llmMs = Math.round(performance.now() - startTime);
  if (second.evaluation.outcome === 'valid') {
    return { tags: second.evaluation.tags, status: 'retry_ok', llmMs, retryCount: 1, attempts };
  }
  return { tags: [], status: 'failed', llmMs, retryCount: 1, attempts };
}
